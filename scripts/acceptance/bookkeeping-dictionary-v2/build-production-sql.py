#!/usr/bin/env python3
"""Build the two production entrypoints from the reviewed migration sources; no DB access."""
from pathlib import Path
import hashlib
import re

ROOT = Path(__file__).resolve().parents[3]
SQL = ROOT / 'iw-packaging-parent/iw-bookkeeping/scripts/dictionary-snapshot-v2'
OUT = SQL / 'production'
OUT.mkdir(exist_ok=True)
names = ['01-schema.sql', '02-backfill.sql', '03-family-initialize.sql', '04-verify.sql']
sources = {name: (SQL / name).read_text() for name in names}
header = '-- Generated by scripts/acceptance/bookkeeping-dictionary-v2/build-production-sql.py.\n'
header += '-- MySQL 8.0.21+ (8.x). Explicit database, backup and stopped writers required.\n'
header += '-- mysql batch mode only: stop on first error; never use --force or interactive SOURCE.\n'
for name, source in sources.items():
    header += '-- SHA256 ' + name + ' ' + hashlib.sha256(source.encode()).hexdigest() + '\n'

# 04 contains no semicolon in a string. Fail loudly if its statement layout changes.
verify = re.sub(r'--[^\n]*', '', sources['04-verify.sql'])
statements = [q.strip() for q in verify.split(';') if q.strip()]
assert len(statements) == 26 and 'unchanged' in statements[23]
assert all(q.startswith(('SELECT', 'WITH')) for q in statements[2:])
labels = ['bill_category', 'unresolved_bills', 'category_snapshot_pair', 'tag_snapshot',
          'duplicate_dict_name', 'dict_name_owner', 'duplicate_successor', 'rename_lineage',
          'budget_category', 'total_budget_category', 'duplicate_budget', 'action_category_missing',
          'action_tags', 'action_category', 'action_tag_list', 'plan_schema', 'task_schema',
          'template_category', 'template_tags', 'family_marker']
checks = [f"SELECT '{label}' check_name, COUNT(*) exception_count FROM (\n{q}\n) exceptions"
          for label, q in zip(labels, statements[3:23])]
checks.append("SELECT 'baseline_changed' check_name, COUNT(*) exception_count FROM (\n" +
              statements[23].rsplit(' ORDER BY b.metric', 1)[0] + '\n) b WHERE unchanged<>1')
checks.append("SELECT 'baseline_missing' check_name, 4-COUNT(*) exception_count FROM bookkeeping_dictionary_migration_baseline WHERE metric IN ('records','wallet','relations','other_dict')")

# Check the actual schema, including an existing same-name index with the wrong definition.
columns = [
 ('base_dict','scope_type','tinyint',False,None,'0'),
 ('base_dict','family_group_id','int',False,None,'0'),
 ('base_dict','previous_id','int',True,None,None),
 ('base_dict','revision','int',False,None,'0'),
 ('base_dict','active_name_key','varbinary',True,128,None),
 ('bookkeeping_records','record_type_id','int',True,None,None),
 ('bookkeeping_records','record_type_name','varchar',True,32,None),
 ('bookkeeping_records','dictionary_snapshot_status','tinyint',False,None,'0'),
 ('bookkeeping_budget','record_type_id','int',True,None,None),
 ('bookkeeping_budget','record_type_name','varchar',True,32,None),
 ('bookkeeping_actions','record_type_id','int',True,None,None),
 ('bookkeeping_record_tag_snapshot','id','int',False,None,None),
 ('bookkeeping_record_tag_snapshot','record_id','int',False,None,None),
 ('bookkeeping_record_tag_snapshot','dict_type','smallint',False,None,None),
 ('bookkeeping_record_tag_snapshot','source_dict_id','int',False,None,None),
 ('bookkeeping_record_tag_snapshot','tag_name','varchar',False,32,None),
 ('bookkeeping_family_dict_state','family_group_id','int',False,None,None),
 ('bookkeeping_family_dict_state','initialized_at','datetime',False,None,'CURRENT_TIMESTAMP'),
]
rows = []
for table, column, dtype, nullable, length, default in columns:
    sqlval = lambda v: 'NULL' if v is None else "'" + str(v) + "'"
    rows.append('SELECT ' + ','.join(sqlval(v) + ' ' + k for k,v in zip(
        ['tbl','col','dtype','nullable','len','defval'],
        [table,column,dtype,'YES' if nullable else 'NO',length,default])))
checks.append("""SELECT 'schema_columns' check_name, COUNT(*) exception_count FROM (
""" + '\nUNION ALL\n'.join(rows) + """
) e LEFT JOIN information_schema.columns c ON c.table_schema=DATABASE() AND c.table_name=e.tbl AND c.column_name=e.col
WHERE c.column_name IS NULL OR c.data_type<>e.dtype OR c.is_nullable<>e.nullable
OR (e.len IS NOT NULL AND c.character_maximum_length<>CAST(e.len AS UNSIGNED))
OR (e.dtype IN ('int','smallint') AND c.column_type NOT LIKE '%unsigned%')
OR (e.dtype='varchar' AND (c.character_set_name<>'utf8mb4' OR c.collation_name<>'utf8mb4_bin'))
OR (e.defval IS NOT NULL AND NOT(UPPER(c.column_default)<=>e.defval))
OR (e.col='active_name_key' AND (c.extra<>'STORED GENERATED' OR c.generation_expression NOT LIKE '%dict_type%'))""")
indexes = [
 ('base_dict','uk_bookkeeping_dict_name',0,'scope_type,family_group_id,user_id,dict_type,active_name_key'),
 ('base_dict','uk_dict_previous',0,'previous_id'),
 ('base_dict','idx_bookkeeping_scope',1,'scope_type,family_group_id,user_id,dict_type,deleted'),
 ('bookkeeping_record_tag_snapshot','PRIMARY',0,'id'),
 ('bookkeeping_record_tag_snapshot','uk_record_tag_source',0,'record_id,dict_type,source_dict_id'),
 ('bookkeeping_record_tag_snapshot','idx_record_tag_type',1,'record_id,dict_type'),
 ('bookkeeping_family_dict_state','PRIMARY',0,'family_group_id'),
]
rows = [f"SELECT '{t}' tbl,'{i}' idx,{n} non_unique,'{c}' cols" for t,i,n,c in indexes]
checks.append("""SELECT 'schema_indexes' check_name,COUNT(*) exception_count FROM (
""" + '\nUNION ALL\n'.join(rows) + """
) e LEFT JOIN (
 SELECT table_name,index_name,non_unique,GROUP_CONCAT(column_name ORDER BY seq_in_index) cols,
 SUM(sub_part IS NOT NULL) prefix_columns,MIN(is_visible) is_visible
 FROM information_schema.statistics WHERE table_schema=DATABASE()
 GROUP BY table_name,index_name,non_unique
) s ON s.table_name=e.tbl AND s.index_name=e.idx
WHERE s.index_name IS NULL OR s.non_unique<>e.non_unique OR s.cols<>e.cols OR s.prefix_columns<>0 OR s.is_visible<>'YES'""")
checks_sql = '\nUNION ALL\n'.join(checks)
summary = "WITH checks AS (\n" + checks_sql + "\n)\nSELECT check_name,exception_count,IF(exception_count=0,'PASS','FAIL') result FROM checks\nUNION ALL SELECT 'OVERALL',SUM(exception_count),IF(SUM(exception_count)=0,'PASS','FAIL') FROM checks;\n"
verify_out = header + '\n' + ';\n'.join(statements[:2]) + ';\nSTART TRANSACTION READ ONLY;\n' + summary
verify_out += "SELECT COUNT(*) total_bills,SUM(dictionary_snapshot_status=1) complete_bills,COALESCE(SUM(amount),0) bill_amount FROM bookkeeping_records;\n"
verify_out += statements[23] + ';\nCOMMIT;\n'
(OUT / '02-verify.sql').write_text(verify_out)

backfill = sources['02-backfill.sql'].split('DROP TEMPORARY TABLE IF EXISTS dict_v2_issues;', 1)[1]
backfill = 'DROP TEMPORARY TABLE IF EXISTS dict_v2_issues;' + backfill.split('CALL iw_dict_v2_assert_backfill();', 1)[0]
backfill = backfill.replace('START TRANSACTION;', '')
family = sources['03-family-initialize.sql'].split('DROP TEMPORARY TABLE IF EXISTS dict_v2_families;', 1)[1]
family = 'DROP TEMPORARY TABLE IF EXISTS dict_v2_families;' + family.split('COMMIT;', 1)[0]
family = family.replace('START TRANSACTION;', '')
apply = header + '\n' + sources['01-schema.sql']
apply += """
DELIMITER $$
DROP PROCEDURE IF EXISTS iw_dict_v2_apply$$
CREATE PROCEDURE iw_dict_v2_apply()
BEGIN
 DECLARE EXIT HANDLER FOR SQLEXCEPTION BEGIN ROLLBACK; RESIGNAL; END;
 START TRANSACTION;
""" + backfill + """
 IF EXISTS(SELECT 1 FROM dict_v2_issues) THEN
  SELECT * FROM dict_v2_issues ORDER BY kind,entity_id,reason;
  SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='STOP: backfill issues; this run is rolled back';
 END IF;
""" + family + """
 DROP TEMPORARY TABLE IF EXISTS dict_v2_checks;
 CREATE TEMPORARY TABLE dict_v2_checks AS
""" + checks_sql + ";\n" + """
 IF EXISTS(SELECT 1 FROM dict_v2_checks WHERE exception_count<>0) THEN
  SELECT * FROM dict_v2_checks WHERE exception_count<>0;
  SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='STOP: verification failed before commit; this run is rolled back';
 END IF;
 COMMIT;
 SELECT 'MIGRATION_PASS' result,
  (SELECT COUNT(*) FROM dict_v2_records) records_migrated_this_run,
  (SELECT COUNT(*) FROM dict_v2_templates WHERE upgraded IS NOT NULL) templates_upgraded_this_run,
  (SELECT COUNT(*) FROM dict_v2_families) families_initialized_this_run;
END$$
DELIMITER ;
CALL iw_dict_v2_apply();
DROP PROCEDURE iw_dict_v2_apply;
"""
(OUT / '01-migrate.sql').write_text(apply)
print('Generated production/01-migrate.sql and production/02-verify.sql')
